let currentEpisode = null
let currentPanel = 0
let lastFocused = null

function openReader(number) {
  const episode = episodes.find(item => item.number === Number(number))
  if (!episode) return
  lastFocused = document.activeElement
  currentEpisode = episode
  currentPanel = 0
  reader.hidden = false
  document.body.classList.add("reader-open")
  renderReader()
  $(".icon-btn", reader).focus({ preventScroll: true })
}

function closeReader() {
  reader.hidden = true
  document.body.classList.remove("reader-open")
  currentEpisode = null
  if (lastFocused && typeof lastFocused.focus === "function") lastFocused.focus({ preventScroll: true })
}

function renderReader() {
  if (!currentEpisode) return
  const panel = currentEpisode.panels[currentPanel]
  const total = currentEpisode.panels.length
  readerNumber.textContent = `Épisode ${String(currentEpisode.number).padStart(2, "0")}`
  readerTitle.textContent = currentEpisode.title
  readerDuration.textContent = currentEpisode.duration
  readerArt.src = panel.art
  readerArt.alt = `${currentEpisode.title} — panneau ${currentPanel + 1}`
  readerArtWrap.className = [
    "reader-art-wrap",
    panel.focus ? `focus-${panel.focus}` : "",
    panel.tone ? `tone-${panel.tone}` : ""
  ].filter(Boolean).join(" ")
  readerCaption.textContent = panel.caption
  readerPanelIndex.textContent = String(currentPanel + 1).padStart(2, "0")
  readerScene.textContent = panel.scene
  readerDialogue.textContent = panel.dialogue
  readerNote.textContent = panel.note
  readerProgressBar.style.width = `${((currentPanel + 1) / total) * 100}%`
  readerCounter.textContent = `Panneau ${currentPanel + 1} / ${total}`
  readerPrev.disabled = currentPanel === 0
  readerNext.textContent = currentPanel === total - 1 ? "Fermer l’épisode ✕" : "Suivant →"
  readerDots.innerHTML = currentEpisode.panels.map((_, index) => `
    <button type="button" class="${index === currentPanel ? "is-active" : ""}" data-panel="${index}" role="tab" aria-selected="${index === currentPanel}" aria-label="Panneau ${index + 1}"></button>
  `).join("")
  const nextPanel = currentEpisode.panels[currentPanel + 1]
  if (nextPanel) {
    const preload = new Image()
    preload.src = nextPanel.art
  }
}

function movePanel(delta) {
  if (!currentEpisode) return
  const next = currentPanel + delta
  if (next < 0 || next >= currentEpisode.panels.length) return
  currentPanel = next
  renderReader()
}

function setupReader() {
  document.addEventListener("click", event => {
    const episodeTrigger = event.target.closest("[data-episode]")
    if (episodeTrigger) {
      event.preventDefault()
      openReader(episodeTrigger.dataset.episode)
      return
    }
    const closeTrigger = event.target.closest("[data-close-reader]")
    if (closeTrigger) {
      closeReader()
      if (closeTrigger.tagName !== "A") event.preventDefault()
      return
    }
    const panelTrigger = event.target.closest("[data-panel]")
    if (panelTrigger && currentEpisode) {
      currentPanel = Number(panelTrigger.dataset.panel)
      renderReader()
    }
  })

  readerPrev.addEventListener("click", () => movePanel(-1))
  readerNext.addEventListener("click", () => {
    if (!currentEpisode) return
    if (currentPanel === currentEpisode.panels.length - 1) closeReader()
    else movePanel(1)
  })

  document.addEventListener("keydown", event => {
    if (reader.hidden) return
    if (event.key === "Escape") {
      event.preventDefault()
      closeReader()
    } else if (event.key === "ArrowLeft") {
      event.preventDefault()
      movePanel(-1)
    } else if (event.key === "ArrowRight") {
      event.preventDefault()
      if (currentEpisode && currentPanel === currentEpisode.panels.length - 1) closeReader()
      else movePanel(1)
    } else if (event.key === "Tab") {
      const focusable = $$("button, a[href]", reader).filter(node => !node.disabled && node.offsetParent !== null)
      if (!focusable.length) return
      const first = focusable[0]
      const last = focusable[focusable.length - 1]
      if (event.shiftKey && document.activeElement === first) {
        event.preventDefault()
        last.focus()
      } else if (!event.shiftKey && document.activeElement === last) {
        event.preventDefault()
        first.focus()
      }
    }
  })
}

function setupNavigation() {
  const toggle = $(".nav-toggle")
  const mobileNav = $("#mobileNav")
  toggle.addEventListener("click", () => {
    const open = toggle.getAttribute("aria-expanded") === "true"
    toggle.setAttribute("aria-expanded", String(!open))
    toggle.setAttribute("aria-label", open ? "Ouvrir le menu" : "Fermer le menu")
    mobileNav.hidden = open
  })
  $$("a, button", mobileNav).forEach(node => node.addEventListener("click", () => {
    toggle.setAttribute("aria-expanded", "false")
    toggle.setAttribute("aria-label", "Ouvrir le menu")
    mobileNav.hidden = true
  }))
}

function setupReveal() {
  const items = $$(".reveal")
  if (!("IntersectionObserver" in window)) {
    items.forEach(item => item.classList.add("is-visible"))
    return
  }
  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible")
        observer.unobserve(entry.target)
      }
    })
  }, { threshold: 0.12, rootMargin: "0px 0px -8% 0px" })
  items.forEach(item => observer.observe(item))
}

async function waitForImages() {
  const images = [...document.images]
  await Promise.all(images.map(image => {
    if (image.complete) return Promise.resolve()
    return new Promise(resolve => {
      image.addEventListener("load", resolve, { once: true })
      image.addEventListener("error", resolve, { once: true })
    })
  }))
}

async function boot() {
  renderEpisodes()
  renderStructure()
  renderCharacters()
  renderPlaces()
  setupReader()
  setupNavigation()
  setupReveal()
  await waitForImages()
  requestAnimationFrame(() => {
    document.documentElement.dataset.captureReady = "true"
    document.body.dataset.ready = "true"
  })
}

boot().catch(error => {
  console.error("Boot failed", error)
  document.documentElement.dataset.captureReady = "error"
})
